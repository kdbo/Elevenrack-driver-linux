# Turn the renders into the editor's assets.
#
#   python3 export.py <renderdir> <device>...
#
# Writes editor/assets/devices/<device>-{body,knob,pointer}.webp (or, for a
# treadle pedal from render_treadle.py, <device>-f00.webp ... one per
# treadle position) and rewrites editor/src/js/device-renders.js with every
# exported device's sizes and the CSS-px centres of its knobs, LED and stomp
# switch (a treadle pedal: its size and frame count).

import json, os, re, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import devices  # noqa: E402

EDITOR = os.path.normpath(os.path.join(HERE, '..', '..'))
ASSETS = os.path.join(EDITOR, 'assets', 'devices')
JS = os.path.join(EDITOR, 'src', 'js', 'device-renders.js')
CSS_PER_CM = 40


def meta(dev):
    s = devices.DEVICES[dev]
    W, H = s['frame']
    at = lambda x, y: [round((x + W / 2) * CSS_PER_CM, 1), round((H / 2 - y) * CSS_PER_CM, 1)]
    return {
        'width': round(W * CSS_PER_CM), 'height': round(H * CSS_PER_CM),
        'knob': round(s['knob']['frame'] * CSS_PER_CM),
        'knobs': {lo: at(*v[:2]) + [v[2] if len(v) > 2 else 1] for lo, v in s['knobs'].items()},
        'led': at(*s['led']),
        'switch': at(*s['switch'][:2]) + [round(s['switch'][2] * CSS_PER_CM, 1)],
        # other controls: centre and size of each one's click area or picker
        'controls': {k: at(*v[:2]) + [round(v[2] * CSS_PER_CM), round(v[3] * CSS_PER_CM)] + list(v[4:5]) for k, v in s.get('controls', {}).items()},
        'leds': {k: at(*v) for k, v in s.get('leds', {}).items()},
        # sliders: the track's minimum end and maximum end (CSS px), the carriage sprite's size and name
        'sliders': {k: at(*a) + at(*b) + [round(s['sprites'][name][1] * CSS_PER_CM), name]
                    for k, (a, b, name) in s.get('sliders', {}).items()},
    }


def read_existing():
    if not os.path.exists(JS):
        return {}
    m = re.search(r'window\.DEVICE_RENDERS = (\{.*\});', open(JS).read(), re.S)
    return json.loads(m.group(1)) if m else {}


def main(src, devs):
    os.makedirs(ASSETS, exist_ok=True)
    all_meta = read_existing()
    for dev in devs:
        if os.path.exists(os.path.join(src, dev + '-image.json')):
            # prepare_image.py: an illustration with each knob cut out of it
            im = json.load(open(os.path.join(src, dev + '-image.json')))
            parts = ['body'] + ['knob-' + k for k in im['knobs']] + ['tog-' + k for k in im.get('toggles', {})] + im.get('sprites', [])
            for part in parts:
                Image.open(os.path.join(src, '%s-%s.png' % (dev, part))).convert('RGBA').save(os.path.join(ASSETS, '%s-%s.webp' % (dev, part)), 'WEBP', quality=90, method=6)
            im['img'] = {'left': 0, 'top': 0, 'width': im['width'], 'height': im.get('img_h', im['height'])}
            im.setdefault('led', [0, 0])
            im.setdefault('switch', [0, 0, 0])
            all_meta[dev] = im
            continue
        if dev == 'plexi-stack':
            # render_amp.py: the head and the cab in perspective, placed against their fronts
            st = json.load(open(os.path.join(src, 'plexi-stack.json')))
            for srcname, dst in (('plexi-head', 'plexi-body'), ('plexi-knob', 'plexi-knob'), ('plexi-pointer', 'plexi-pointer'), ('cab-412', 'cab-412-body')):
                Image.open(os.path.join(src, srcname + '.png')).convert('RGBA').save(os.path.join(ASSETS, dst + '.webp'), 'WEBP', quality=90, method=6)
            all_meta['plexi'] = {'width': 760, 'height': 290, 'img': st['plexi-head'], 'knob': st['knob'], 'knobs': st['knobs'], 'led': st['led'], 'switch': [0, 0, 0]}
            all_meta['cab-412'] = {'img': st['cab-412'], 'plate': st['plate']}
            continue
        frames = sorted(f for f in os.listdir(src) if re.fullmatch(re.escape(dev) + r'-f\d\d\.png', f))
        if frames:
            for f in frames:
                Image.open(os.path.join(src, f)).convert('RGBA').save(os.path.join(ASSETS, f[:-4] + '.webp'), 'WEBP', quality=86, method=6)
            w, h = Image.open(os.path.join(src, frames[0])).size
            all_meta[dev] = {'frames': len(frames), 'width': w // 2, 'height': h // 2}
            continue
        for part, q in [('body', 88), ('knob', 92), ('pointer', 92)] + [(n, 92) for n in devices.DEVICES[dev].get('sprites', {})]:
            im = Image.open(os.path.join(src, '%s-%s.png' % (dev, part))).convert('RGBA')
            im.save(os.path.join(ASSETS, '%s-%s.webp' % (dev, part)), 'WEBP', quality=q, method=6)
        all_meta[dev] = meta(dev)
    with open(JS, 'w') as f:
        f.write('// Generated by editor/tools/render-devices/export.py: sizes of the rendered\n'
                '// device looks and the CSS-px centres of their controls. Do not edit.\n')
        f.write('window.DEVICE_RENDERS = ' + json.dumps(all_meta, indent=1, sort_keys=True) + ';\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2:])
